class StructuredReportOutput(BaseModel):
    """Output for the project report generation with visible and context layers."""

    visible: ReportVisible
    context: ReportContext = Field(default_factory=ReportContext)


class SuggestedQuestionsOutput(BaseModel):
    """Output for generated suggested follow-up questions."""

