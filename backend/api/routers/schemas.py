# ── Guided Report Requirements ─────────────────────────────────────────────


class RequirementOption(BaseModel):
    id: str
    label: str
    description: str
    recommended: bool = False
    normalized_value: dict[str, Any] = Field(default_factory=dict)


class RequirementQuestion(BaseModel):
    id: str
    section: str
    step: int
    total_steps: int
    title: str
    prompt: str
    expected_fields: list[str]
    options: list[RequirementOption]
    allow_custom_answer: bool = True
    placeholder: str
    status: Literal["unanswered", "answered", "needs_review"] = "unanswered"
    answered: bool = False
    answer: str | None = None
    selected_option_id: str | None = None


class RequirementQuestionsResponse(BaseModel):
    questions: list[RequirementQuestion]


class RequirementAnswerRequest(BaseModel):
    question_id: str
    selected_option_id: str | None = None
    custom_answer: str | None = None
    expected_version: int | None = None


class RequirementAnswerResponse(BaseModel):
    report: ReportOut | None = None
    preloaded: bool = False
    accepted: bool
    status: Literal["answered", "needs_clarification"]
    normalized_value: dict[str, Any]
    missing_fields: list[str] = Field(default_factory=list)
    clarification_prompt: str | None = None


class RequirementValidationOutput(BaseModel):
    accepted: bool = True
    normalized_value: dict[str, Any] = Field(default_factory=dict)
    missing_fields: list[str] = Field(default_factory=list)
    clarification_prompt: str | None = None
    display_answer: str = ""
